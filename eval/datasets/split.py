"""Stratified split plans with deterministic hash-ranked selection.

Issue #7: a fixed-seed 50/450 split of the 500 LongMemEval-S questions,
stratified by capability category (question_type) and the abstention
flag, with no overlap, full coverage and abstention questions on both
sides; plus the fixed 8-question smoke list (one per question_type and
two abstention questions, drawn from the development split only so
smoke runs never touch the holdout set).

Determinism does not rely on any RNG implementation detail: every dev
member is chosen by a sha256 ranking of (seed, stratum, handle), so the
plan is a pure function of the input multiset and the seed. The plan
artifacts (split.json / smoke.json, committed under eval/datasets/
splits/) therefore regenerate byte-identically from the pinned data
file, and the committed manifests carry the seed and algorithm id for
reproduction.
"""

from __future__ import annotations

import hashlib
from typing import Sequence

from pydantic import Field, model_validator

from eval.contracts.common import ContractError, SchemaVersionedModel
from eval.datasets.longmemeval import SplitItem

SPLIT_ALGORITHM = "stratified-hashrank@1"
SMOKE_ALGORITHM = "smoke-hashrank@1"

#: Fixed seeds (issue #7); recorded verbatim in the committed artifacts.
SPLIT_SEED = "hippo-longmemeval-s-split@1"
SMOKE_SEED = "hippo-longmemeval-s-smoke@1"

#: Committed split artifact directory (regenerated by scripts/make_split.py).
SPLIT_DIR_NAME = "longmemeval_s_cleaned"


def hash_rank(seed: str, scope: str, handle: str) -> str:
    """Deterministic selection key; never depends on gold membership."""
    return hashlib.sha256(
        "|".join((seed, scope, handle)).encode("utf-8")
    ).hexdigest()


def stratum_key(item: SplitItem) -> str:
    """Stratum id: question_type x abstention flag."""
    return f"{item.question_type}|{'abs' if item.is_abstention else 'ans'}"


class StratumCount(SchemaVersionedModel):
    total: int = Field(ge=1)
    dev: int = Field(ge=0)

    @model_validator(mode="after")
    def _bounds(self) -> "StratumCount":
        if self.dev > self.total:
            raise ValueError(f"dev {self.dev} exceeds stratum total {self.total}")
        if self.total >= 2 and not (1 <= self.dev <= self.total - 1):
            raise ValueError(
                f"strata with >=2 members must appear on BOTH sides "
                f"(total={self.total}, dev={self.dev})"
            )
        return self


class SplitPlan(SchemaVersionedModel):
    """Committed 50/450 split manifest (reproducible from seed + data)."""

    dataset_plan: str = Field(min_length=1)
    source_sha256: str = Field(min_length=64, max_length=64)
    algorithm: str = Field(min_length=1)
    seed: str = Field(min_length=1)
    dev_size: int = Field(ge=1)
    total_size: int = Field(ge=2)
    strata: dict[str, StratumCount]
    dev_ids: tuple[str, ...]
    holdout_ids: tuple[str, ...]

    @model_validator(mode="after")
    def _invariants(self) -> "SplitPlan":
        dev, hold = set(self.dev_ids), set(self.holdout_ids)
        if len(dev) != len(self.dev_ids) or len(hold) != len(self.holdout_ids):
            raise ValueError("duplicate ids inside a split side")
        if dev & hold:
            raise ValueError(
                f"the two sides overlap on {sorted(dev & hold)[:5]}"
            )
        if len(dev) + len(hold) != self.total_size:
            raise ValueError(
                f"dev {len(dev)} + holdout {len(hold)} != total "
                f"{self.total_size}; the union must cover every question"
            )
        if len(dev) != self.dev_size:
            raise ValueError(f"dev side has {len(dev)} ids, expected {self.dev_size}")
        if sum(s.total for s in self.strata.values()) != self.total_size:
            raise ValueError("stratum totals do not sum to total_size")
        if sum(s.dev for s in self.strata.values()) != len(dev):
            raise ValueError("stratum dev counts do not sum to the dev size")
        abs_dev = sum(s.dev for k, s in self.strata.items() if k.endswith("|abs"))
        abs_total = sum(s.total for k, s in self.strata.items() if k.endswith("|abs"))
        if abs_total >= 2 and (abs_dev == 0 or abs_dev == abs_total):
            raise ValueError(
                "abstention questions must appear on BOTH sides "
                f"(abs total={abs_total}, dev={abs_dev})"
            )
        return self


class SmokePlan(SchemaVersionedModel):
    """Committed 8-question smoke manifest (semantics aligned with the M1
    offline smoke subset: six question_type ids plus two abstention ids,
    all drawn from the development split)."""

    dataset_plan: str = Field(min_length=1)
    source_sha256: str = Field(min_length=64, max_length=64)
    split_sha256: str = Field(min_length=64, max_length=64)
    algorithm: str = Field(min_length=1)
    seed: str = Field(min_length=1)
    smoke_ids: tuple[str, ...]
    per_question_type: dict[str, str]
    abstention_ids: tuple[str, ...]

    @model_validator(mode="after")
    def _invariants(self) -> "SmokePlan":
        if len(self.smoke_ids) != 8 or len(set(self.smoke_ids)) != 8:
            raise ValueError("the smoke subset must be exactly 8 distinct ids")
        if len(self.per_question_type) != 6:
            raise ValueError(
                "the smoke subset must cover all six question types once"
            )
        if len(self.abstention_ids) != 2:
            raise ValueError("the smoke subset must contain two abstention ids")
        if not set(self.abstention_ids) <= set(self.smoke_ids):
            raise ValueError("abstention_ids must be part of smoke_ids")
        if not set(self.per_question_type.values()) <= set(self.smoke_ids):
            raise ValueError("per_question_type ids must be part of smoke_ids")
        if set(self.abstention_ids) & set(self.per_question_type.values()):
            raise ValueError(
                "abstention ids and per-type ids must be disjoint (types "
                "are covered by non-abstention questions)"
            )
        return self


def _content_sha256(plan: SchemaVersionedModel) -> str:
    return hashlib.sha256(plan.model_dump_json().encode("utf-8")).hexdigest()


def allocate_dev(totals: dict[str, int], dev_size: int) -> dict[str, int]:
    """Largest-remainder allocation with both-sides coverage guarantees.

    Deterministic: remainder order is (fraction desc, key asc) and every
    guarantee repair moves from/to the stratum with the most/least slack
    (key asc on ties), so the allocation is a pure function of totals.
    """
    total_n = sum(totals.values())
    if not 0 < dev_size < total_n:
        raise ContractError(
            code="split_infeasible",
            message=(
                f"dev_size {dev_size} must be strictly between 0 and the "
                f"total {total_n}"
            ),
            location="(allocation)",
        )
    quota = {k: n * dev_size / total_n for k, n in totals.items()}
    dev = {k: int(q) for k, q in quota.items()}

    def fill_up() -> bool:
        candidates = [k for k in totals if dev[k] < totals[k]]
        if not candidates:
            return False
        k = min(candidates, key=lambda k: (-(quota[k] - dev[k]), k))
        dev[k] += 1
        return True

    while sum(dev.values()) < dev_size:
        if not fill_up():
            raise ContractError(
                code="split_infeasible",
                message=f"cannot allocate {dev_size} dev ids",
                location="(allocation)",
            )

    def drain_down() -> bool:
        candidates = [k for k in totals if dev[k] > 0]
        if not candidates:
            return False
        k = min(candidates, key=lambda k: ((quota[k] - dev[k]), k))
        dev[k] -= 1
        return True

    while sum(dev.values()) > dev_size:
        if not drain_down():
            raise ContractError(
                code="split_infeasible",
                message=f"cannot shrink allocation to {dev_size}",
                location="(allocation)",
            )

    # Guarantee: every stratum with >=2 members appears on both sides.
    for k in sorted(totals):
        n = totals[k]
        if n < 2:
            continue
        if dev[k] == 0:
            donors = [d for d in totals if dev[d] >= 2]
            if not donors:
                raise ContractError(
                    code="split_infeasible",
                    message=f"stratum {k!r} cannot enter the dev side",
                    location="(allocation)",
                )
            donor = sorted(donors, key=lambda d: (-dev[d], d))[0]
            dev[donor] -= 1
            dev[k] += 1
        elif dev[k] == n:
            takers = [d for d in totals if dev[d] <= totals[d] - 2]
            if not takers:
                raise ContractError(
                    code="split_infeasible",
                    message=f"stratum {k!r} cannot keep a holdout member",
                    location="(allocation)",
                )
            taker = min(takers, key=lambda d: (totals[d] - dev[d], d))
            dev[k] -= 1
            dev[taker] += 1
    assert sum(dev.values()) == dev_size
    return dev


def stratified_split(
    items: Sequence[SplitItem],
    *,
    dev_size: int,
    seed: str,
    dataset_plan: str,
    source_sha256: str,
    algorithm: str = SPLIT_ALGORITHM,
) -> SplitPlan:
    """Build the SplitPlan: allocation + hash-ranked member selection."""
    handles = [i.handle for i in items]
    if len(set(handles)) != len(handles):
        raise ContractError(
            code="duplicate_sample_handle",
            message="split input contains duplicate handles",
            location="(items)",
        )
    members: dict[str, list[SplitItem]] = {}
    for item in items:
        members.setdefault(stratum_key(item), []).append(item)
    totals = {k: len(v) for k, v in members.items()}
    alloc = allocate_dev(totals, dev_size)

    dev_ids: list[str] = []
    holdout_ids: list[str] = []
    for key in sorted(members):
        ranked = sorted(
            members[key], key=lambda i: (hash_rank(seed, key, i.handle), i.handle)
        )
        dev_ids.extend(i.handle for i in ranked[: alloc[key]])
        holdout_ids.extend(i.handle for i in ranked[alloc[key] :])

    return SplitPlan(
        dataset_plan=dataset_plan,
        source_sha256=source_sha256,
        algorithm=algorithm,
        seed=seed,
        dev_size=dev_size,
        total_size=len(items),
        strata={k: StratumCount(total=totals[k], dev=alloc[k]) for k in sorted(totals)},
        dev_ids=tuple(sorted(dev_ids)),
        holdout_ids=tuple(sorted(holdout_ids)),
    )


def select_smoke(
    dev_items: Sequence[SplitItem],
    *,
    seed: str,
    dataset_plan: str,
    source_sha256: str,
    split: SplitPlan,
    algorithm: str = SMOKE_ALGORITHM,
) -> SmokePlan:
    """Pick the 8 smoke ids from the DEV side only (holdout stays untouched).

    One non-abstention question per question_type (lowest hash rank) plus
    the two lowest-ranked abstention questions; deterministic and order
    independent.
    """
    dev_set = set(split.dev_ids)
    pool = [i for i in dev_items if i.handle in dev_set]
    if len(pool) != len(dev_set):
        raise ContractError(
            code="split_input_mismatch",
            message=(
                f"dev_items covers {len(pool)} handles but the split dev "
                f"side has {len(dev_set)}"
            ),
            location="(items)",
        )
    per_type: dict[str, str] = {}
    for qtype in sorted({i.question_type for i in pool if not i.is_abstention}):
        ranked = sorted(
            (i for i in pool if i.question_type == qtype and not i.is_abstention),
            key=lambda i: (hash_rank(seed, f"smoke|{qtype}", i.handle), i.handle),
        )
        if not ranked:
            raise ContractError(
                code="split_infeasible",
                message=(
                    f"the dev side has no non-abstention question of type "
                    f"{qtype!r}; the smoke subset needs all six types"
                ),
                location="(smoke)",
            )
        per_type[qtype] = ranked[0].handle
    abst_ranked = sorted(
        (i for i in pool if i.is_abstention),
        key=lambda i: (hash_rank(seed, "smoke|abs", i.handle), i.handle),
    )
    if len(abst_ranked) < 2:
        raise ContractError(
            code="split_infeasible",
            message=(
                f"the dev side has only {len(abst_ranked)} abstention "
                "questions; the smoke subset needs two"
            ),
            location="(smoke)",
        )
    abstention_ids = tuple(i.handle for i in abst_ranked[:2])
    smoke_ids = tuple(sorted([*per_type.values(), *abstention_ids]))
    return SmokePlan(
        dataset_plan=dataset_plan,
        source_sha256=source_sha256,
        split_sha256=_content_sha256(split),
        algorithm=algorithm,
        seed=seed,
        smoke_ids=smoke_ids,
        per_question_type=per_type,
        abstention_ids=abstention_ids,
    )
